export function pickRandomWord() {
  if (FIVE_LETTER_WORDS.length === 0) {
    console.error('❌ No 5-letter words available!');
    return { word: 'KOSONG', category: 'Error', hint: 'Tidak ada kata tersedia' };
  }
  
  const randomItem = FIVE_LETTER_WORDS[Math.floor(Math.random() * FIVE_LETTER_WORDS.length)];
  console.log('🎯 Selected word:', randomItem.word, 
              'Length:', randomItem.word.length, 
              'Category:', randomItem.category, 
              'Hint:', randomItem.hint);
  
  return randomItem;
}

export function isValidWord(word) {
  const upperWord = word.toUpperCase();
  const isValid = FIVE_LETTER_WORDS.some(item => item.word === upperWord);
  console.log(`🔍 Checking: "${upperWord}" - Valid: ${isValid}`);
  return isValid;
}

export function getWordHint(word) {
  const wordObj = FIVE_LETTER_WORDS.find(item => item.word === word.toUpperCase());
  return wordObj ? { category: wordObj.category, hint: wordObj.hint } : null;
}